import * as React from "react";
import { cn } from "@/lib/utils";

export interface CardProps extends React.HTMLAttributes<HTMLDivElement> {
  hoverEffect?: boolean;
}

export const Card = React.forwardRef<HTMLDivElement, CardProps>(
  ({ className, hoverEffect = false, ...props }, ref) => {
    return (
      <div
        ref={ref}
        className={cn(
          "rounded-[var(--radius-lg)] border border-[var(--border)] bg-[var(--card)] p-6 md:p-8 text-[var(--foreground)] transition-colors duration-200",
          hoverEffect && "hover:border-[var(--border-hover)] hover:bg-[var(--card-hover)]",
          className
        )}
        {...props}
      />
    );
  }
);
Card.displayName = "Card";

